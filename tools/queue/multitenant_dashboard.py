#!/usr/bin/env python3
"""Generate the focused dashboard from queue claims and dated acceptance metadata."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

import yaml

ROOT = Path(__file__).resolve().parents[2]
STATUS = ROOT / "docs/30-design/tenancy/multitenant-delivery-status.json"
OUTPUT = ROOT / "docs/30-design/tenancy/multitenant-delivery-dashboard.md"
ROADMAP = "multitenant-delivery-roadmap-2026-11-02.md"
STAGES = {
    "local-accepted": "Locally accepted",
    "incorporated-pending": "Incorporated; testing pending",
    "integrated-accepted": "Integrated acceptance recorded",
}
STATES = {"in-progress", "blocked", "not-started", "promoted"}


def cell(value):
    return str(value).replace("|", r"\|").replace("\n", " ")


def anchor(value):
    return value.lower()


def validate(data, items, roadmap):
    ids = [m["id"] for m in data["milestones"]]
    if len(set(ids)) != len(ids) or set(ids) != {f"M{i}" for i in range(7)}:
        raise ValueError("milestones must uniquely cover M0 through M6")
    work = [w["id"] for w in data["work"]]
    if len(work) != len(set(work)) or any(w not in items for w in work):
        raise ValueError("dashboard work must uniquely reference existing queue IDs")
    dependencies = {}
    for m in data["milestones"]:
        if m["state"] not in STATES or any(w not in work for w in m["work"]):
            raise ValueError("invalid milestone state or work reference")
        if any(d not in ids or d == m["id"] for d in m["requires"]):
            raise ValueError("invalid milestone prerequisite")
        dependencies[m["id"]] = m["requires"]
    visiting, visited = set(), set()

    def visit(node):
        if node in visiting:
            raise ValueError("cyclic milestone prerequisites")
        if node in visited:
            return
        visiting.add(node)
        for dep in dependencies[node]:
            visit(dep)
        visiting.remove(node)
        visited.add(node)

    for node in ids:
        visit(node)
    for item in data["slices"]:
        if item["stage"] not in STAGES or item["work"] not in work:
            raise ValueError("invalid slice stage or work reference")
        if not re.fullmatch(r"[a-f0-9]{8,40}", item["commit"]):
            raise ValueError("slice commit must be explicit")
        # These evidence headings use plain ASCII words, punctuation and dates.
        headings = re.findall(r"^### (.+)$", roadmap, re.M)
        anchors = {re.sub(r"[^a-z0-9 -]", "", h.lower()).replace(" ", "-") for h in headings}
        if item["evidence"] not in anchors:
            raise ValueError("missing roadmap evidence anchor: " + item["evidence"])


def render(data, queue, roadmap):
    items = {i["id"]: i for i in queue["items"]}
    validate(data, items, roadmap)
    lines = [
        "<!-- Generated by tools/queue/multitenant_dashboard.py. Edit the queue and multitenant-delivery-status.json. -->",
        "# Multitenant delivery: working dashboard", "",
        f"**Recorded {data['as_of']}; not a live branch monitor.** "
        f"Observed integration tip: `{data['observed_tip']}` on `{data['integration']}`.",
        data["integration_note"], "",
        "**Start here:** use the dependency map for sequencing, the lane table for parallel work, "
        "and the acceptance ledger for what has actually passed. No milestone is promoted by a completed dependency slice.",
        "",
        f"[Decisions and detailed acceptance]({ROADMAP}) | "
        "[Programme overview](../../../site/pages/nightscout-next-gen-platform.html) | "
        "[Full queue](../../../queue/QUEUE.md)", "",
        "## Acceptance stages", "",
        "**Locally accepted -> incorporated / testing pending -> integrated acceptance recorded -> milestone promoted.** "
        "Incorporation is ancestry, not a passing test run. Stages below are dated evidence claims, "
        "not freshly executed gates. Queue states remain claims too; use `make queue-status` for measurements. "
        "Counts are not additive and are not completion percentages.", "",
        "## Milestone dependencies", "",
        "Arrows mean prerequisite -> dependent, **not progress**. These are the roadmap's milestone edges; "
        "work-item prerequisites appear separately below. M2 and M5 have additional work gates, "
        "not a claim that they can finish without storage/runtime foundations.", "",
        "```mermaid", "flowchart LR",
    ]
    for m in data["milestones"]:
        lines.append(f'  {m["id"]}["{m["id"]}: {m["title"]}<br/>{m["state"]}"]')
    for m in data["milestones"]:
        for dep in m["requires"]:
            lines.append(f'  {dep} --> {m["id"]}')
    lines.extend([
        "  classDef active fill:#e2eff0,stroke:#1d6b73,color:#17262a",
        "  classDef waiting fill:#fbf1dc,stroke:#8a5a00,color:#17262a",
        "  classDef planned fill:#f6f8f8,stroke:#55686d,color:#17262a",
    ])
    for m in data["milestones"]:
        style = {"in-progress": "active", "blocked": "waiting", "not-started": "planned", "promoted": "active"}[m["state"]]
        lines.append(f'  class {m["id"]} {style}')
    lines.extend(["```", "", "| Milestone | Claimed status | Prerequisites / work gates | Remaining promotion gate |",
                  "|---|---|---|---|"])
    for m in data["milestones"]:
        deps = ", ".join(m["requires"] + [f'[{w}](#{anchor(w)})' for w in m["work"]]) or "Acceptance gate at right"
        lines.append(f'| **{m["id"]}: {cell(m["title"])}** | {m["state"]} | {deps} | {cell(m["gate"])} |')
    lines.extend(["", "## Parallel lanes and next gates", "",
                  "Lane labels describe the recorded handoff, not a live assignment service. "
                  "Confirm ownership before taking an unassigned lane. An in-progress prerequisite may support "
                  "a dormant prototype; it does not authorize serving or promote its dependent.", "",
                  "<details markdown=\"1\">", "<summary>Work-item dependency map (direct edges from the queue)</summary>", "",
                  "```mermaid", "flowchart LR"])
    work_ids = {w["id"] for w in data["work"]}
    graph_ids = work_ids | {d for w in work_ids for d in items[w].get("blocks_on", [])}
    for work_id in sorted(graph_ids):
        lines.append(f'  {work_id}["{work_id}<br/>{items[work_id]["state"]}"]')
    for work_id in sorted(work_ids):
        for dep in items[work_id].get("blocks_on", []):
            lines.append(f"  {dep} --> {work_id}")
    lines.extend(["```", "", "External prerequisites are shown one level deep; the full queue owns their further dependencies.",
                  "", "</details>", "",
                  "| Work item / queue claim | Lane | Queue prerequisites (claimed state) | Next bounded action |",
                  "|---|---|---|---|"])
    for w in data["work"]:
        item = items[w["id"]]
        deps = ", ".join(f'{d} ({items[d]["state"]})' for d in item.get("blocks_on", [])) or "None recorded"
        lines.append(f'| <a id="{anchor(w["id"])}"></a>**{w["id"]}**: {cell(item["state"])} | '
                     f'{cell(w["lane"])} | {cell(deps)} | {cell(w["next"])} |')
    lines.extend(["", "## Accepted slices and integration handoff", "",
                  "A bounded slice below does **not** close its parent queue card or M0-M6.", "",
                  "| Slice / parent | Acceptance stage | Commit / evidence | Recorded result and boundary |",
                  "|---|---|---|---|"])
    for s in data["slices"]:
        lines.append(f'| {cell(s["title"])} / [{s["work"]}](#{anchor(s["work"])}) | '
                     f'**{STAGES[s["stage"]]}** | [`{s["commit"]}`]({ROADMAP}#{s["evidence"]}) | {cell(s["result"])} |')
    lines.extend(["", "## Deferred and separate lanes", "", "| Candidate | Lane | Boundary / dependency |", "|---|---|---|"])
    for d in data["deferred"]:
        lines.append(f'| {cell(d["title"])} | {cell(d["lane"])} | {cell(d["reason"])} |')
    lines.extend(["", "## Updating this dashboard", "",
                  "1. Update `queue/work-queue.yaml` for work states and real prerequisites. "
                  "Do not duplicate those edges in the status overlay.",
                  "2. Append measured evidence to the roadmap; update `multitenant-delivery-status.json` "
                  "for dated slice stages, integration tip, lanes and remaining milestone gates. "
                  "Use explicit commit/results; do not promote on ancestry alone.",
                  "3. Run `python tools/queue/multitenant_dashboard.py`, then "
                  "`python tools/queue/multitenant_dashboard.py --check`, `make queue-check` and `make site-check`. "
                  "Commit the source and generated view together. Publishing remains a separate maintainer action.", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated dashboard is stale")
    args = parser.parse_args()
    try:
        text = render(json.loads(STATUS.read_text()), yaml.safe_load((ROOT / "queue/work-queue.yaml").read_text()),
                      (OUTPUT.parent / ROADMAP).read_text())
    except (ValueError, KeyError) as error:
        parser.exit(1, f"dashboard: {error}\n")
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            parser.exit(1, "dashboard: stale; run python tools/queue/multitenant_dashboard.py\n")
        print("dashboard: current")
    else:
        OUTPUT.write_text(text)
        print(f"dashboard: wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
