#!/usr/bin/env python3
"""Turn results/metrics.json into one markdown table per diagram (base renders, plus the
mutated render's displacement)."""
import json
import sys

rows = json.load(open(sys.argv[1]))


def frac(v):
    return "-" if v is None else f"{v[0]}/{v[1]}"


print("# STPA diagram lab: measured results\n")
print("Generated by `report.py` from `metrics.json`; lower is better except the loop columns.\n")
print("| column | meaning |\n|---|---|")
print("| levels | node pairs drawn out of hierarchy order (higher level not above lower) |")
print("| columns | same-level pairs drawn out of left-to-right lane order |")
print("| ctl left | loop pairs whose control path runs left of its feedback path |")
print("| distinct | loop pairs whose control and feedback paths stay more than 6 px apart |")
print("| cross | edge crossings away from nodes |")
print("| overlap | edge pairs drawn on top of each other |")
print("| through | edges passing through a node they do not connect |")
print("| groups | outside nodes inside a group's hull |")
print("| labels | text runs overlapping another text run (more than 15% of the smaller) |")
print("| moved | mean / max node displacement after adding one feedback edge, as a fraction of the drawing |")
print()
for dia in sorted({r["diagram"] for r in rows}):
    print(f"## {dia}\n")
    print("| variant | levels | columns | ctl left | distinct | cross | overlap | through | groups | labels | moved | size | src lines |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in [r for r in rows if r["diagram"] == dia and r["mode"] == "base"]:
        mut = next((m for m in rows if m["diagram"] == dia and m["mode"] == "mutated" and m["variant"] == r["variant"]), {})
        if r.get("error") or r["found"]["missing_nodes"] or r["found"]["missing_edges"]:
            f = r.get("found", {})
            print(f"| {r['variant']} | not scored: {r.get('error') or 'missing nodes ' + str(f['missing_nodes']) + ' edges ' + str(f['missing_edges'])} ||||||||||||")
            continue
        d = mut.get("displacement")
        moved = f"{d['mean']:.2f} / {d['max']:.2f}" if d else "-"
        print(f"| {r['variant']} | {frac(r['level_violations'])} | {frac(r['column_violations'])} | "
              f"{frac(r['loops_control_left'])} | {frac(r['loops_distinct'])} | {r['crossings']} | {r['edge_overlaps']} | "
              f"{r['edges_through_nodes']} | {'-' if r['group_intrusions'] is None else r['group_intrusions']} | {r['label_collisions']} | {moved} | "
              f"{r['width']}x{r['height']} | {r['source_lines'] or '-'} |")
    print()
