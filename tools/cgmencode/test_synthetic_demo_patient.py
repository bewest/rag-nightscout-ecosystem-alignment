"""Tests for the synthetic demonstration patient generator."""
from __future__ import annotations

import json

from tools.cgmencode import synthetic_demo_patient as gen
from tools.cgmencode.run_synthetic_demo_report import banner_text


def test_deterministic_for_a_seed():
    a = gen.generate(seed=7, days=2)
    b = gen.generate(seed=7, days=2)
    assert json.dumps(a, sort_keys=True) == json.dumps(b, sort_keys=True)
    c = gen.generate(seed=8, days=2)
    assert json.dumps(a, sort_keys=True) != json.dumps(c, sort_keys=True)


def test_nightscout_shapes_and_utc_profile():
    data = gen.generate(seed=1, days=2)
    store = data["profile"][0]["store"]["Default"]
    assert store["timezone"] == "Etc/UTC"
    assert {"basal", "sens", "carbratio", "target_low"} <= set(store)
    # CGM every 5 minutes, minus the sensor warm-up gap.
    assert all(e["type"] == "sgv" and 39 <= e["sgv"] <= 400
               for e in data["entries"])
    assert 2 * 288 - 24 <= len(data["entries"]) <= 2 * 288
    kinds = {t["eventType"] for t in data["treatments"]}
    assert {"Temp Basal", "Correction Bolus", "Carb Correction"} <= kinds
    ds = data["devicestatus"][0]
    assert ds["device"].startswith("loop://")
    assert {"iob", "cob", "predicted", "enacted"} <= set(ds["loop"])


def test_write_marks_output_synthetic(tmp_path):
    gen.write(tmp_path, seed=3, days=1)
    for name in ("entries", "treatments", "devicestatus", "profile"):
        assert (tmp_path / f"{name}.json").exists()
    note = (tmp_path / "SYNTHETIC.txt").read_text()
    assert "seed 3" in note and "No real person's data" in note


def test_banner_names_generator_and_seed():
    text = banner_text(42)
    assert text.startswith("Synthetic demonstration data: generated by "
                           "tools/cgmencode/synthetic_demo_patient.py "
                           "with seed 42; no real person's data.")
    assert "they are not advice for anyone" in text
