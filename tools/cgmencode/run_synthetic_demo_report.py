"""Build the synthetic demonstration clinical decision report.

SYNTHETIC DATA ONLY. Generates Loop-style Nightscout collections with
``tools.cgmencode.synthetic_demo_patient`` (seeded, deterministic), runs
the same ``tools.ns2parquet convert`` ingestion and
``tools.cgmencode.analyze_patient.analyze`` pipeline used for real
reports, and writes the deliverables to
``reports/synthetic-demo-analysis/``. Nothing under ``externals/ns-data``
or ``externals/ns-parquet`` is read.

The intermediate JSON and parquet go to ``externals/synthetic-demo/``
(gitignored) unless ``--work-dir`` says otherwise.

Usage:
    python -m tools.cgmencode.run_synthetic_demo_report [--seed N] [--days 90]
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

from tools.cgmencode import synthetic_demo_patient as gen

REPO = Path(__file__).resolve().parents[2]
PATIENT_ID = "synthetic-demo"
OUT_DIR = REPO / "reports/synthetic-demo-analysis"
WORK_DIR = REPO / "externals/synthetic-demo"
TITLE_PREFIX = "Synthetic demonstration"


def banner_text(seed: int) -> str:
    return (f"Synthetic demonstration data: generated by {gen.GENERATOR_PATH} "
            f"with seed {seed}; no real person's data. The recommendations "
            f"show what the prototype produces; they are not advice for "
            f"anyone.")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--seed", type=int, default=gen.DEFAULT_SEED)
    p.add_argument("--days", type=int, default=gen.DEFAULT_DAYS)
    p.add_argument("--work-dir", default=str(WORK_DIR))
    p.add_argument("--output", default=str(OUT_DIR))
    args = p.parse_args(argv)

    work = Path(args.work_dir)
    json_dir, parquet_dir = work / "json", work / "parquet"
    for d in (json_dir, parquet_dir):
        if d.exists():
            shutil.rmtree(d)
    counts = gen.write(json_dir, seed=args.seed, days=args.days)
    print(f"Synthetic collections: {counts}")
    subprocess.run(
        [sys.executable, "-m", "tools.ns2parquet", "convert",
         "-i", str(json_dir), "-p", PATIENT_ID, "-o", str(parquet_dir), "-q"],
        check=True, cwd=str(REPO))

    # Record a repo-relative parquet path in the outputs, not a local one.
    try:
        parquet_rel = Path(os.path.relpath(parquet_dir.resolve(), REPO))
    except ValueError:
        parquet_rel = parquet_dir
    os.chdir(REPO)

    from tools.cgmencode.analyze_patient import analyze
    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=True)
    analyze(PATIENT_ID, parquet_rel, out,
            banner=banner_text(args.seed), title_prefix=TITLE_PREFIX)


if __name__ == "__main__":
    main()
